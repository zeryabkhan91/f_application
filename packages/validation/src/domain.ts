export const currencyCodeSchema = z.string().regex(/^[A-Z]{3}$/);
// Financial JSON values are decimal strings; binary floating-point is never authoritative.
export const moneySchema = z.string().regex(/^-?\d{1,16}(?:\.\d{1,2})?$/);
export const quantitySchema = z.string().regex(/^-?\d{1,14}(?:\.\d{1,4})?$/);
export const organizationSelectionSchema = z
